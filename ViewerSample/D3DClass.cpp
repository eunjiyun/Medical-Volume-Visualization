	adapter->Release();
	adapter = 0;

	// ??ë¸ê½…???¶ì†ë¹˜çŒ¿?ëª´???ê³¸ì «??ëªƒë¹??
	factory->Release();
	factory = 0;

	// ???±ë„ç­Œï½‹?????Œë“¼??™ã—??? ?Î»?ƒç”±??‰Â€??€???ˆë¼„

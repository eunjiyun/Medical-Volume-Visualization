	// ??????ê³—ì¡Š?????±ì Ÿ??ëªƒë¹??
	float fieldOfView = XM_PI / 4.0f;
	float screenAspect = (float)screenWidth / (float)screenHeight;

	// 3D ?????­Œ?»ë‚¯??è¢ã‚‹ë¦???????ê³—ì¡Š??ç­Œë¾??¸°???ˆë¼„

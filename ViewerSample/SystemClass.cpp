void SystemClass::Run()
{
	// 嶺뚮∥???낆?? ??뚮벣??쇻럸???諛댁뎽 ???貫?껆뵳??
	MSG msg;
	ZeroMemory(&msg, sizeof(MSG));

	// ??????夷?遊붋????リ턁筌?嶺뚮∥???낆?????꾩룇猷?????긺춯?뼿 嶺뚮∥???낆???猷먮쳜?딆뜾紐??筌먲퐢鍮??
	while (true)
	{
		// ???덉┣??嶺뚮∥???낆????嶺뚳퐣瑗???紐껊퉵??
		if (PeekMessage(&msg, NULL, 0, 0, PM_REMOVE))
		{
			// ??リ턁筌?嶺뚮∥???낆?????꾩룇猷???롪퍔???嶺뚮∥???낆?? ?猷먮쳜?딆뜾紐????뀀??紐껊퉵??
			if (msg.message == WM_QUIT)
				break;

			TranslateMessage(&msg);
			DispatchMessage(&msg);
		}
		else
		{
			// ???筌뤾쑬???Frame ??貫???嶺뚳퐣瑗???紐껊퉵??
			if (!Frame())
				break;
		}
	}
}



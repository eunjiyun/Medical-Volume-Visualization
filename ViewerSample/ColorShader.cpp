bool ColorShader::SetShaderParameters(ID3D11DeviceContext* deviceContext, XMMATRIX worldMatrix, XMMATRIX viewMatrix, XMMATRIX projectionMatrix)
{
	// ??ê³—ì¡Š??transpose??ë¤¿ì—° ??¨ì€¬ëµ ??ºìš©?????????????—ì“º ??ëªƒë¹??
	worldMatrix = XMMatrixTranspose(worldMatrix);
	viewMatrix = XMMatrixTranspose(viewMatrix);
	projectionMatrix = XMMatrixTranspose(projectionMatrix);

	// ??¨ëªƒ???•ê³Œ??????ê³¸ë’ ?????????ˆì¦²????«ë²????ˆë¼„.
	D3D11_MAPPED_SUBRESOURCE mappedResource;
	if (FAILED(deviceContext->Map(m_matrixBuffer, 0, D3D11_MAP_WRITE_DISCARD, 0, &mappedResource)))
	{
		return false;
	}

	// ??¨ëªƒ???•ê³Œ??????¨ì€¬ëµ ??¨ì€«í“  ?????????? ?¶ì›??ï§ê¾©ê¸???ˆë¼„.
	MatrixBufferType* dataPtr = (MatrixBufferType*)mappedResource.pData;

	// ??¨ëªƒ???•ê³Œ??????ê³—ì¡Š???°ê·£ë²Šæ²…??ëªƒë¹??
	dataPtr->world = worldMatrix;
	dataPtr->view = viewMatrix;
	dataPtr->projection = projectionMatrix;

	// ??¨ëªƒ???•ê³Œ??????«ë²?????ê³•ë¹??
	deviceContext->Unmap(m_matrixBuffer, 0);

	// ?ï§ã…¼????¨ì€¬ëµ ??ºìš©???ë½°ë²¥ ??¨ëªƒ???•ê³Œ?????è¢â‘º??????±ì Ÿ??ëªƒë¹??
	unsigned bufferNumber = 0;

	// ç­Œë¾??ç­Œë¾ë§???—??ï§ã…¼????¨ì€¬ëµ ??ºìš°ë²???¨ëªƒ???•ê³Œ??ê³?ª´??„ì…?€???¶ì…????—??„ì…?????ˆë¼„.
	deviceContext->VSSetConstantBuffers(bufferNumber, 1, &m_matrixBuffer);

	return true;
}


